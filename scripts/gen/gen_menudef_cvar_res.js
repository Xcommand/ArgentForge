// Packs the scraped cvar dictionary into the resource the menu constructor reads.
//
// The field a widget's `command` argument fills in is a cvar name, and a name typed wrong is a
// setting that silently does nothing. So the constructor offers the names the engine really
// declares, with what each one holds and what the engine's own menu calls it, and this file is
// how that reaches the program.
//
//   node scripts/gen/gen_menudef_cvar_res.js
// Reads out/scratch/menudef_cvars.txt (gen_menudef_cvars.js), writes
// dist/res/config/menudef_cvars.cfg.

const fs   = require('fs');
const path = require('path');

const repo = path.join(__dirname, '..', '..');
const src  = path.join(repo, 'out/scratch/menudef_cvars.txt');
const out  = path.join(repo, 'dist/res/config/menudef_cvars.cfg');

if (!fs.existsSync(src))
{
	console.log(`no ${path.relative(repo, src)} - run gen_menudef_cvars.js with the engine source first`);
	process.exit(1);
}

// name, type, default, flags, callback, hidden, in_menus, label, english
const raw = fs.readFileSync(src, 'utf8');
// The command names travel as a comment line so every reader of this table sees only cvar
// rows. No command means the scrape had no engine source, not that the engine has none
const commands = [...new Set(((raw.match(/^# commands\t(.*)$/m) || [, ''])[1]).split(',').filter(Boolean))]
	.sort((a, b) => a.localeCompare(b));

const rows = raw.split(/\r?\n/)
	.filter(l => l && !l.startsWith('#'))
	.map(l => l.split('\t'))
	.filter(c => c.length >= 9 && c[0]);

const clean = text => text.replace(/["|]/g, ' ').trim();
// The scrape writes '-' where the engine has no English words for a cvar. Keeping the dash
// would read as a value called "minus"
const words = text => {
	const one = clean(text);
	return one == '-' ? '' : one;
};
const seen  = new Set();
const list  = [];

for (const c of rows)
{
	if (seen.has(c[0])) continue;
	seen.add(c[0]);
	// A hidden cvar isn't meant to be offered to a user at all, but it is still legal to name,
	// so it goes last rather than being dropped: dropping it would make the constructor say a
	// real cvar doesn't exist
	list.push({
		name: c[0],
		text: `${clean(c[1])}|${clean(c[2])}|${words(c[8])}`,
		menu: Number(c[6]) > 0,
		hidden: c[5] === 'hidden',
	});
}

list.sort((a, b) => (a.hidden - b.hidden) || (b.menu - a.menu) || a.name.localeCompare(b.name));

// The engine's own menu file, which declares value tables and menus a mod can point at
// without declaring them itself: 'Option "$X", "cl_run", "OnOff"' uses the game's OnOff
function engineNames(file)
{
	if (!fs.existsSync(file))
	{
		console.log(`no ${file}, so the base names won't be offered`);
		return { tables: [], menus: [] };
	}
	const tables = [], menus = [];
	for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/))
	{
		const one = line.match(/^\s*(\w+)\s+"([^"]+)"/);
		if (!one) continue;
		const word = one[1].toLowerCase();
		if (word == 'optionvalue' || word == 'optionstring') tables.push(one[2]);
		else if (word == 'optionmenu' || word == 'listmenu' || word == 'imagescroller') menus.push(one[2]);
	}
	const distinct = list => [...new Set(list)].sort((a, b) => a.localeCompare(b));
	return { tables: distinct(tables), menus: distinct(menus) };
}

const uz    = process.env.UZDOOM_SRC || process.argv[2] || '';
const names = uz ? engineNames(path.join(uz, 'wadsrc/static/menudef.txt')) : { tables: [], menus: [] };

const lines = [];
lines.push('// Cvar names the menu constructor offers for a widget command');
lines.push('//');
lines.push('// Generated by scripts/gen/gen_menudef_cvar_res.js out of the dictionary that');
lines.push('// scripts/gen/gen_menudef_cvars.js scrapes from the engine, so a name here is a');
lines.push('// name the engine declares. The value is type|default|what the engine menu calls it');
lines.push('//');
lines.push('// A name that is not in here is not an error: mods declare their own cvars in');
lines.push('// ZScript and C++, and the field stays free to type in.');
lines.push('cvars');
lines.push('{');
for (const one of list)
	lines.push(`\t${one.name} = "${one.text}";`);
lines.push('}');
lines.push('');
lines.push('// Value tables the game itself declares, which a mod option can point at');
lines.push('// without writing them out again');
lines.push('valuetables');
lines.push('{');
lines.push(`\tall = { ${names.tables.join(', ')} }`);
lines.push('}');
lines.push('');
lines.push('// Menus the game itself declares, which a Submenu can open');
lines.push('menus');
lines.push('{');
lines.push(`\tall = { ${names.menus.join(', ')} }`);
lines.push('}');
lines.push('');
lines.push('// Console commands the engine registers with CCMD(name). A Command or SafeCommand');
lines.push("// line runs one of these, or several of them joined by ';', which is how a mod");
lines.push('// menu closes itself and starts a map at once');
lines.push('commands');
lines.push('{');
lines.push(`\tall = { ${commands.join(', ')} }`);
lines.push('}');

// The resource reader takes 'name = value' and nothing else, and it refuses the whole file over
// one line it can't read, so a mistake here turns into an empty list everywhere
const body = lines.filter(l => l && !l.startsWith('//'));
for (let i = 0; i < body.length; i++)
{
	const line = body[i].trim();
	if (!line || line == '{' || line == '}') continue;
	if (!line.includes('=') && (body[i + 1] || '').trim() != '{')
	{
		console.log(`refusing to write a line the resource reader can't parse: ${line}`);
		process.exit(1);
	}
}

fs.writeFileSync(out, lines.join('\r\n') + '\r\n');
console.log(`written: ${path.relative(repo, out)}`);
console.log(`${list.length} cvars, ${list.filter(c => c.menu).length} of them in the engine's own menus, ${commands.length} console commands`);
